import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import type { DbAccessGrantInfo, DbAssignmentInfo, DbCredentials } from '@eat/shared';
import { matchDbAssignments } from '@eat/shared';
import { Api } from '../src/client.js';
import { dbAccessList, dbAccessResetPassword, dbAccessRevoke, dbCredentialsPull, dbCredentialsRun, dbRun } from '../src/commands/db.js';

const ID_A = '11111111-1111-4111-8111-111111111111';
const ID_B = '22222222-2222-4222-8222-222222222222';
const ID_C = '33333333-3333-4333-8333-333333333333';

function assignment(id: string, dbName: string, instanceName: string, status = 'active'): DbAssignmentInfo {
  return {
    id,
    dbName,
    instanceName,
    status,
    instanceId: instanceName,
    instanceHost: 'db.local',
    instancePort: 5432,
    engine: 'postgres',
    dbUser: `u_${dbName}`,
    purpose: 'x',
    requesterId: 'u',
    requesterName: '小王',
    decidedByName: null,
    hasCredentials: true,
    error: null,
    createdAt: '',
    updatedAt: '',
  } as DbAssignmentInfo;
}

const MINE = [
  assignment(ID_A, 'crm', '测试 PG'),
  assignment(ID_B, 'shared', '测试 PG'),
  assignment(ID_C, 'shared', '备用 PG'),
];

const CRED: DbCredentials = {
  assignmentId: ID_A,
  engine: 'postgres',
  host: 'db.local',
  port: 5432,
  database: 'crm',
  user: 'u_crm',
  password: "p'w#1",
  url: 'postgres://u_crm:p\'w%231@db.local:5432/crm',
};

let dir: string;
let stdout: string;

function grant(dbName = 'analytics', instanceName = '测试 PG', instanceId = '测试 PG'): DbAccessGrantInfo {
  return { id: 'grant-reader', catalogId: 'catalog-reader', dbName, instanceName, instanceId, userId: 'reader', userName: '读者', level: 'read', state: 'active', error: null, canManage: false, updatedAt: '' };
}

function fixture(grants: DbAccessGrantInfo[] = []) {
  const request = vi.fn(async (method: string, url: string) => {
    if (method === 'GET' && url === '/api/db/assignments/mine') return MINE;
    if (method === 'GET' && url === '/api/db/access/grants?scope=mine') return grants;
    if (method === 'POST' && url.endsWith('/credentials')) return { ...CRED, assignmentId: url.split('/')[4] };
    throw new Error(`unexpected ${method} ${url}`);
  });
  vi.spyOn(Api, 'fromSaved').mockReturnValue({ request } as unknown as Api);
  return request;
}

beforeEach(() => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'eat-db-'));
  stdout = '';
  vi.spyOn(console, 'log').mockImplementation(() => {});
  vi.spyOn(console, 'error').mockImplementation(() => {});
  vi.spyOn(process.stdout, 'write').mockImplementation((chunk) => {
    stdout += String(chunk);
    return true;
  });
});
afterEach(() => {
  vi.restoreAllMocks();
  fs.rmSync(dir, { recursive: true, force: true });
});

describe('matchDbAssignments', () => {
  it('认 id、库名、库名@实例名；已删除的不按名字命中', () => {
    expect(matchDbAssignments(MINE, ID_B).map((a) => a.id)).toEqual([ID_B]);
    expect(matchDbAssignments(MINE, ' crm ').map((a) => a.id)).toEqual([ID_A]);
    expect(matchDbAssignments(MINE, 'shared')).toHaveLength(2);
    expect(matchDbAssignments(MINE, 'shared@备用 PG').map((a) => a.id)).toEqual([ID_C]);
    expect(matchDbAssignments([assignment(ID_A, 'old', 'x', 'deleted')], 'old')).toEqual([]);
  });
});

describe('eat db credentials pull', () => {
  it('按库名找到分配，默认写 .env：DB_* 加 DATABASE_URL，带 eat 标记，值按 dotenv 规则引用', async () => {
    const request = fixture();
    const out = path.join(dir, '.env');
    await dbCredentialsPull('crm', { out });
    expect(request).toHaveBeenCalledWith('POST', `/api/db/assignments/${ID_A}/credentials`);
    const text = fs.readFileSync(out, 'utf8');
    expect(text.split('\n')[0]).toMatch(/^# Generated by eat — eat db credentials pull crm @ /);
    expect(text).toContain('DB_HOST=db.local\nDB_PORT=5432\nDB_NAME=crm\nDB_USER=u_crm\n');
    expect(text).toContain(`DB_PASSWORD="p'w#1"`);
    expect(text).toContain('DATABASE_URL=');
  });

  it('同名库在两台实例上：报错并给出「库名@实例名」的写法，不取任何凭证', async () => {
    const request = fixture();
    await expect(dbCredentialsPull('shared', { print: true })).rejects.toThrow(/shared@测试 PG[\s\S]*shared@备用 PG/);
    expect(request).not.toHaveBeenCalledWith('POST', expect.anything());
    await dbCredentialsPull('shared@备用 PG', { print: true });
    expect(request).toHaveBeenCalledWith('POST', `/api/db/assignments/${ID_C}/credentials`);
  });

  it('名下没有时列出可用的库；完整 id 不查清单直接取（管理员取别人的）', async () => {
    const request = fixture();
    await expect(dbCredentialsPull('nope', { print: true })).rejects.toThrow(/可用的有：crm、shared@测试 PG、shared@备用 PG/);
    request.mockClear();
    await dbCredentialsPull(ID_B, { print: true });
    expect(request).toHaveBeenCalledExactlyOnceWith('POST', `/api/db/assignments/${ID_B}/credentials`);
  });

  it('--print --format shell 只打印 export 语句；--format 不带 --print 直接拒绝', async () => {
    fixture();
    await dbCredentialsPull('crm', { print: true, format: 'shell' });
    expect(stdout).toContain(`export DB_PASSWORD='p'\\''w#1'\n`);
    await expect(dbCredentialsPull('crm', { format: 'json' })).rejects.toThrow(/--format 只用于 --print/);
    await expect(dbCredentialsPull('crm', { print: true, format: 'yaml' })).rejects.toThrow(/dotenv \/ shell \/ json \/ url/);
  });

  it('--print --format url 只输出连接串一行，可直接喂给 psql', async () => {
    fixture();
    await dbCredentialsPull('crm', { print: true, format: 'url' });
    expect(stdout).toBe(`${CRED.url}\n`);
  });

  it('已有手写 .env 时中止不覆盖；--merge 只改 DB_* 几行，其余原样保留', async () => {
    fixture();
    const out = path.join(dir, '.env');
    fs.writeFileSync(out, 'APP_PORT=8080\nDB_HOST=old\n');
    await expect(dbCredentialsPull('crm', { out })).rejects.toThrow(/不是 eat 生成的/);
    expect(fs.readFileSync(out, 'utf8')).toBe('APP_PORT=8080\nDB_HOST=old\n');
    await dbCredentialsPull('crm', { out, merge: true });
    const merged = fs.readFileSync(out, 'utf8');
    expect(merged.startsWith('APP_PORT=8080\nDB_HOST=db.local\n')).toBe(true);
    expect(merged).toContain('DB_NAME=crm');
  });
});

describe('eat db credentials run', () => {
  it('凭证只注入子进程：子进程读得到 DB_* 与 DATABASE_URL，退出码透传，不写任何文件', async () => {
    const request = fixture();
    const out = path.join(dir, 'seen.json');
    const script = `require('fs').writeFileSync(${JSON.stringify(out)}, JSON.stringify({ user: process.env.DB_USER, password: process.env.DB_PASSWORD, url: process.env.DATABASE_URL })); process.exit(3)`;
    try {
      await dbCredentialsRun('crm', [process.execPath, '-e', script]);
      expect(process.exitCode).toBe(3);
    } finally {
      process.exitCode = undefined;
    }
    expect(request).toHaveBeenCalledWith('POST', `/api/db/assignments/${ID_A}/credentials`);
    expect(JSON.parse(fs.readFileSync(out, 'utf8'))).toEqual({ user: 'u_crm', password: CRED.password, url: CRED.url });
    expect(fs.readdirSync(dir)).toEqual(['seen.json']);
    // 当前进程自己的环境没被污染
    expect(process.env.DB_PASSWORD).toBeUndefined();
  });

  it('漏写命令时不取凭证、直接报错', async () => {
    const request = fixture();
    await expect(dbCredentialsRun('crm', [])).rejects.toThrow(/eat db credentials run <库> -- <命令/);
    expect(request).not.toHaveBeenCalled();
  });
});


describe('分配与个人授权共用名字解析', () => {
  it('授权持有人可以run授权的库，且同库同时有分配时优先owner凭证', async () => {
    const request = fixture([grant(), grant('crm')]);
    try {
      await dbCredentialsRun('analytics', [process.execPath, '-e', 'process.exit(process.env.DB_PASSWORD ? 7 : 9)']);
      expect(process.exitCode).toBe(7);
      expect(request).toHaveBeenCalledWith('POST', '/api/db/access/catalog/catalog-reader/credentials');
      request.mockClear();
      await dbCredentialsRun('crm', [process.execPath, '-e', 'process.exit(0)']);
      expect(request).toHaveBeenCalledWith('POST', `/api/db/assignments/${ID_A}/credentials`);
      expect(request).not.toHaveBeenCalledWith('POST', '/api/db/access/catalog/catalog-reader/credentials');
    } finally { process.exitCode = undefined; }
  });
});


