CREATE TABLE "site_cdn" (
	"id" integer PRIMARY KEY DEFAULT 1 NOT NULL,
	"enabled" boolean DEFAULT false NOT NULL,
	"scope" text DEFAULT 'overseas' NOT NULL,
	"credential_source" text DEFAULT 'independent' NOT NULL,
	"access_key_id_encrypted" text,
	"access_key_secret_encrypted" text,
	"origin_secret_encrypted" text NOT NULL,
	"auto_dns" boolean DEFAULT false NOT NULL,
	"status" text DEFAULT 'disabled' NOT NULL,
	"connected" boolean DEFAULT false NOT NULL,
	"phase" text DEFAULT '' NOT NULL,
	"last_error" text DEFAULT '' NOT NULL,
	"cname" text DEFAULT '' NOT NULL,
	"resources" jsonb DEFAULT '{}'::jsonb NOT NULL,
	"dns_instructions" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"certificate_expires_at" timestamp with time zone,
	"origin_certificate_checked_at" timestamp with time zone,
	"certificate_synced_at" timestamp with time zone,
	"certificate_sync_error" text DEFAULT '' NOT NULL,
	"retry_at" timestamp with time zone,
	"attempts" integer DEFAULT 0 NOT NULL,
	"drain_until" timestamp with time zone,
	"actor_id" uuid,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
