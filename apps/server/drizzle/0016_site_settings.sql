CREATE TABLE "site_setting" (
	"id" integer PRIMARY KEY DEFAULT 1 NOT NULL,
	"status" text DEFAULT 'disabled' NOT NULL,
	"domain" text NOT NULL,
	"platform_url" text DEFAULT '' NOT NULL,
	"oss_region" text NOT NULL,
	"oss_bucket" text NOT NULL,
	"oss_access_key_id_encrypted" text NOT NULL,
	"oss_access_key_secret_encrypted" text NOT NULL,
	"tls_mode" text NOT NULL,
	"acme_email" text DEFAULT '' NOT NULL,
	"dns_access_key_id_encrypted" text,
	"dns_access_key_secret_encrypted" text,
	"certificate_id" text DEFAULT '' NOT NULL,
	"resolver_name" text DEFAULT '' NOT NULL,
	"platform_application_id" text NOT NULL,
	"upstream_url" text DEFAULT '' NOT NULL,
	"upstream_port" integer DEFAULT 3000 NOT NULL,
	"gateway_target" text NOT NULL,
	"auto_dns" boolean DEFAULT false NOT NULL,
	"route_configured" boolean DEFAULT false NOT NULL,
	"resource_key" uuid DEFAULT gen_random_uuid() NOT NULL,
	"server_id" text,
	"operation_id" uuid,
	"operation_started_at" timestamp with time zone,
	"checks" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"last_error" text DEFAULT '' NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
